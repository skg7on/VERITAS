std::vector<SanitizerFrameLocation>
ParseSanitizerFrameLocations(std::string_view text) {
  std::vector<SanitizerFrameLocation> frames;
  size_t line = 0;
  while (line < text.size()) {
    size_t next = text.find('\n', line);
    if (next == std::string_view::npos)
      next = text.size();
    std::string_view row = text.substr(line, next - line);
    // The second stack (the overflowing frame's own locals) is not execution
    // evidence; stop at its header.
    if (row.find("is located in stack of thread") != std::string_view::npos)
      break;
    size_t cursor = 0;
    while (cursor < row.size() && row[cursor] == ' ')
      ++cursor;
    bool frame_row = cursor < row.size() && row[cursor] == '#' &&
                     cursor + 1 < row.size() && row[cursor + 1] >= '0' &&
                     row[cursor + 1] <= '9';
    if (frame_row) {
      // Frames may carry several parenthesised groups (module location and a
      // build id). The module location is the one with a `+0x...` offset.
      size_t at = cursor;
      while ((at = row.find('(', at)) != std::string_view::npos) {
        const auto close = row.find(')', at);
        if (close == std::string_view::npos)
          break;
        std::string_view location = row.substr(at + 1, close - at - 1);
        const auto plus = location.rfind('+');
        bool accepted = false;
        if (plus != std::string_view::npos) {
          std::string_view value = location.substr(plus + 1);
          uint64_t offset = 0;
          bool valid = value.size() > 2 && value[0] == '0' &&
                       (value[1] == 'x' || value[1] == 'X');
          for (size_t i = 2; valid && i < value.size(); ++i) {
            char c = value[i];
            if (c >= '0' && c <= '9')
              offset = offset * 16 + static_cast<uint64_t>(c - '0');
            else if (c >= 'a' && c <= 'f')
              offset = offset * 16 + static_cast<uint64_t>(c - 'a' + 10);
            else if (c >= 'A' && c <= 'F')
              offset = offset * 16 + static_cast<uint64_t>(c - 'A' + 10);
            else
              valid = false;
          }
          if (valid) {
            std::string_view module = location.substr(0, plus);
            std::string architecture;
            const auto colon = module.rfind(':');
            if (colon != std::string_view::npos) {
              std::string_view suffix = module.substr(colon + 1);
              // Darwin appends `:arch`; an ELF module path may contain a colon
              // only as part of a filename, never as this token shape.
              if (!suffix.empty() &&
                  suffix.find_first_of("/ .\\\"") == std::string_view::npos) {
                architecture = std::string(suffix);
                module = module.substr(0, colon);
              }
            }
            frames.push_back(
                {std::string(module), std::move(architecture), offset});
            accepted = true;
          }
        }
        if (accepted)
          break;
        at = close + 1;
      }
    }
    line = next + 1;
  }
  return frames;
}

StatusOr<ReplayConfig> DecodeReplayConfig(const Json &value) {
  const auto *object = value.getAsObject();
  if (!object)
    return Bad("replay configuration must be an object");
  const std::set<std::string> allowed = {
      "producer",        "version",     "compiler",
      "isolation",       "work_parent", "deny_read_paths",
      "read_only_paths", "harnesses",   "limits"};
  for (const auto &[key, unused] : *object)
    if (!allowed.contains(key))
      return Bad("unknown replay configuration key: " + key);
  ReplayConfig config;
  if (object->getString("producer"))
    config.producer = Text(*object, "producer");
  if (config.producer != "asan-replay.v1")
    return Bad("unregistered replay producer");
  if (object->getString("version"))
    config.version = Text(*object, "version");
  if (config.version.empty())
    return Bad("replay producer version is required");
  if (!object->getString("compiler"))
    return Bad("replay compiler is required");
  config.compiler = Text(*object, "compiler");
  if (config.compiler.empty() || config.compiler.front() != '/' ||
      !ProfileSafe(config.compiler))
    return Bad("replay compiler must be a safe absolute path");
  if (object->getString("isolation"))
    config.isolation = Text(*object, "isolation");
  if (config.isolation != "" && config.isolation != kMacIsolation &&
      config.isolation != kLinuxIsolation)
    return Bad("unknown replay isolation profile");
  if (object->getString("work_parent"))
    config.work_parent = Text(*object, "work_parent");
  if (config.work_parent.empty()) {
#ifdef __APPLE__
    config.work_parent = "/private/tmp";
#else
    config.work_parent = "/tmp";
#endif
  }
  if (config.work_parent.front() != '/' || !ProfileSafe(config.work_parent))
    return Bad("replay work parent must be a safe absolute path");
  if (const auto *deny = object->getArray("deny_read_paths")) {
    for (const auto &item : *deny) {
      auto path = item.getAsString();
      if (!path || path->empty() || path->front() != '/' || !ProfileSafe(*path))
        return Bad("replay deny path must be a safe absolute path");
      config.deny_read_paths.push_back(*path);
    }
  }
  if (const auto *allowed_paths = object->getArray("read_only_paths")) {
    for (const auto &item : *allowed_paths) {
      auto path = item.getAsString();
      if (!path || path->empty() || path->front() != '/' || !ProfileSafe(*path))
        return Bad("replay read-only path must be a safe absolute path");
      config.read_only_paths.push_back(*path);
    }
  }
  if (const auto *harnesses = object->getObject("harnesses")) {
    for (const auto &[key, item] : *harnesses) {
      const auto *harness = item.getAsObject();
      if (key.empty() || !harness || harness->size() != 2 ||
          !harness->getString("source") || !harness->getString("payload"))
        return Bad("invalid replay harness entry");
      ReplayHarness entry{Text(*harness, "source"), Text(*harness, "payload")};
      if (entry.source.empty() || entry.source.front() != '/' ||
          entry.payload.empty() || entry.payload.front() != '/' ||
          !ProfileSafe(entry.source) || !ProfileSafe(entry.payload))
        return Bad("replay harness paths must be safe and absolute");
      config.harnesses.emplace(key, std::move(entry));
    }
  }
  if (const auto *limits = object->getObject("limits")) {
    const std::set<std::string> keys = {"wall_ms", "output_bytes", "rss_bytes",
                                        "max_processes"};
    for (const auto &[key, unused] : *limits)
      if (!keys.contains(key))
        return Bad("unknown replay limit: " + key);
    for (const auto &[key, item] : *limits)
      if (!item.getAsUINT64() || !*item.getAsUINT64())
        return Bad("replay limits must be positive");
    if (limits->get("wall_ms"))
      config.limits.wall_ms = Number(*limits, "wall_ms");
    if (limits->get("output_bytes"))
      config.limits.output_bytes = Number(*limits, "output_bytes");
    if (limits->get("rss_bytes"))
      config.limits.rss_bytes = Number(*limits, "rss_bytes");
    if (limits->get("max_processes"))
      config.limits.max_processes = Number(*limits, "max_processes");
    if (config.limits.wall_ms > 120000 ||
        config.limits.output_bytes > 1024 * 1024 ||
        config.limits.rss_bytes > 2ull * 1024 * 1024 * 1024 ||
        config.limits.max_processes > 32)
      return Bad("replay limits exceed the hard protocol allowances");
  }
  return config;
}

StatusOr<AdmittedReplayCommand>
AdmitReplayCompileCommand(const ReviewSnapshot &snapshot,
                          const CapturedCompileCommand &command,
                          std::string_view input_root) {
  if (command.arguments.empty())
    return Unsupported("captured command has no compiler");
  const auto driver = Path(command.arguments[0]).filename().string();
  if (driver != "clang" && driver != "clang++")
    return Unsupported("captured command uses an unadmitted compiler/wrapper");
  AdmittedReplayCommand admitted;
  admitted.source = command.file;
  bool source_seen = false;
  const std::set<std::string> standards = {
      "c11",   "c17",   "c23",   "gnu11",   "gnu17",   "gnu23",   "c++14",
      "c++17", "c++20", "c++23", "gnu++14", "gnu++17", "gnu++20", "gnu++23"};
  for (size_t i = 1; i < command.arguments.size(); ++i) {
    const std::string &argument = command.arguments[i];
    auto value = [&]() -> StatusOr<std::string> {
      if (++i == command.arguments.size() || command.arguments[i].empty())
        return Bad("captured compiler flag is missing its operand");
      return command.arguments[i];
    };
    if (argument == "-c" || argument == "-MD" || argument == "-MMD" ||
        argument == "-MP")
      continue;
    if (argument == "-o" || argument == "-MF" || argument == "-MT" ||
        argument == "-MQ") {
      auto ignored = value();
      if (!ignored.ok())
        return ignored.status();
      continue;
    }
    if (argument.starts_with("-std=")) {
      if (!standards.contains(argument.substr(5)))
        return Unsupported("unadmitted captured language standard: " +
                           argument);
      admitted.flags.push_back(argument);
      continue;
    }
    if (argument == "--target" || argument == "-target" ||
        argument.starts_with("--target=")) {
      return Unsupported(
          "captured explicit target cannot be replayed on this host");
    }
    if (argument == "-x") {
      auto language = value();
      if (!language.ok())
        return language.status();
      if (*language != "c" && *language != "c++")
        return Unsupported("unadmitted captured language");
      admitted.language = *language;
      continue;
    }
    if (argument == "-D" || argument == "-U" || argument.starts_with("-D") ||
        argument.starts_with("-U")) {
      auto macro = argument.size() == 2
                       ? value()
                       : StatusOr<std::string>(argument.substr(2));
      if (!macro.ok() || macro->empty() ||
          macro->find_first_of("\n\r") != std::string::npos ||
          macro->find('\0') != std::string::npos)
        return Unsupported("unadmitted captured macro operand");
      admitted.flags.push_back(argument.substr(0, 2) + *macro);
      continue;
    }
    bool directory = argument == "-I" || argument == "-isystem" ||
                     argument == "-iquote" ||
                     (argument.starts_with("-I") && argument.size() > 2);
    if (directory) {
      const std::string flag = argument.starts_with("-I") ? "-I" : argument;
      auto include = argument.starts_with("-I") && argument.size() > 2
                         ? StatusOr<std::string>(argument.substr(2))
                         : value();
      if (!include.ok())
        return include.status();
      auto path = snapshot.CompilerPath(command.directory, *include);
      if (!path.ok())
        return Unsupported("captured include path is outside the snapshot");
      std::string rewritten = *path == "."
                                  ? std::string(input_root)
                                  : std::string(input_root) + "/" + *path;
      // Preserve the include kind; -isystem/-iquote are not interchangeable
      // with -I for system-header shadowing.
      admitted.flags.push_back(flag);
      admitted.flags.push_back(std::move(rewritten));
      continue;
    }
    static const std::set<std::string> switches = {
        "-pthread",  "-fno-exceptions",
        "-fno-rtti", "-fexceptions",
        "-frtti",    "-fPIC",
        "-fpic",     "-fPIE",
        "-g",        "-O0",
        "-O1",       "-O2",
        "-O3",       "-Os",
        "-Oz",       "-Wall",
        "-Wextra",   "-Werror",
        "-pedantic"};
    if (switches.contains(argument)) {
      admitted.flags.push_back(argument);
      continue;
    }
    if (argument.starts_with('-') || argument.starts_with('@'))
      return Unsupported("unadmitted captured compiler flag: " + argument);
    auto path = snapshot.CompilerPath(command.directory, argument);
    if (!path.ok() || *path != command.file || source_seen)
      return Unsupported("unexpected captured positional input");
    source_seen = true;
  }
  if (!source_seen)
    return Unsupported("captured command has no source operand");
  if (admitted.language.empty()) {
    // Same rule as the structural index: a C driver plus a C extension is C;
    // everything else is C++. An explicit -x above wins.
    const auto extension = Path(command.file).extension().string();
    admitted.language =
        driver == "clang" && (extension == ".c" || extension == ".h") ? "c"
                                                                      : "c++";
  }
  return admitted;
}

StatusOr<ReplayResult> RunAsanReplay(const Json &request,
                                     const ReplayConfig &config,
                                     const ReviewSnapshot &snapshot,
                                     const StructuralIndex &index,
                                     uint64_t deadline_ms) {
  auto valid = ValidateVerificationRequest(request);
  if (!valid.ok())
    return valid;

  // Isolation is checked before any compiler is invoked. There is no
  // unconfined fallback.
  if (config.isolation.empty())
    return Unsupported("no enforcing isolation profile configured");
  if (config.isolation != kMacIsolation && config.isolation != kLinuxIsolation)
    return Unsupported("unknown isolation profile");

  const auto &q = *request.getAsObject();
  const auto &binding = *q.getObject("binding");
  const auto &domain = *q.getObject("execution_domain");
  const auto &operands = *q.getObject("typed_operands");
  const auto replay_start = Clock::now();
  const uint64_t request_budget = std::min(
      Number(*q.getObject("budget"), "wall_ms"), config.limits.wall_ms);
  const uint64_t total_budget =
      deadline_ms ? std::min(deadline_ms, request_budget) : request_budget;
  auto remaining = [&]() -> uint64_t {
    const uint64_t elapsed = static_cast<uint64_t>(
        std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now() -
                                                              replay_start)
            .count());
    return elapsed >= total_budget ? 0 : total_budget - elapsed;
  };
  auto expired = [&]() {
    return Status::DeadlineExceeded("replay exceeded its total budget");
  };
  if (*binding.get("snapshot_id") != *domain.get("snapshot_id") ||
      snapshot.binding().snapshot_id->value() != *binding.get("snapshot_id") ||
      ToJson(snapshot.binding()) != *q.get("binding") ||
      ToJson(index.binding()) != *q.get("binding"))
    return Bad("replay request does not match the pinned snapshot/index");
  if (Text(q, "predicate_kind") != "copy_bound.v1" ||
      Text(operands, "kind") != "copy_bound.v1")
    return Bad("unsupported replay predicate");
  if (Text(q, "backend_id") != config.producer ||
      Text(q, "backend_version") != config.version)
    return Bad("request names an unregistered replay producer");

  const auto &callsite_json = *operands.getObject("callsite_ref");
  auto index_id =
      ParseArtifactId<StructuralIndexTag>(*callsite_json.getString("index_id"));
  if (!index_id.ok())
    return index_id.status();
  const auto ordinal =
      static_cast<uint32_t>(*callsite_json.get("ordinal")->getAsUINT64());
  if (*index_id != index.id() || ordinal >= index.entities().size() ||
      index.entities()[ordinal].kind != "CALLSITE")
    return Bad("callsite is not an advertised structural index entity");
  const auto callsite = EntityRef{index.id(), ordinal};
  const uint64_t capacity = Number(operands, "capacity_bytes");
  const uint64_t requested = Number(operands, "requested_bytes");
  const uint64_t readable = Number(operands, "readable_bytes");
  const std::string harness_id = Text(operands, "harness_id");
  const std::string payload_digest = Text(operands, "payload_digest");
  if (Text(domain, "harness_id") != harness_id ||
      Text(domain, "input_digest") != payload_digest)
    return Bad("concrete input domain does not match the typed operands");
  if (requested > readable)
    return Bad("requested bytes exceed the declared readable extent");

  const auto max_examined = Number(*q.getObject("budget"), "examined");
  auto evidence = InvestigateLocal({index,
                                    snapshot.binding(),
                                    "copy_bound.v1",
                                    callsite,
                                    {"EXTENT", "OPERANDS"},
                                    max_examined});
  if (!evidence.ok())
    return Unsupported("local evidence is unavailable: " +
                       std::string(evidence.status().message()));
  const CopyOperands *operand_refs = nullptr;
  uint64_t extent = 0;
  bool have_extent = false;
  for (const auto &observation : evidence->observations) {
    if (observation.slot == "OPERANDS")
      operand_refs = &std::get<CopyOperands>(observation.value);
    if (observation.slot == "EXTENT") {
      extent = std::get<ByteExtent>(observation.value).bytes;
      have_extent = true;
    }
  }
  if (!have_extent || !operand_refs)
    return Unsupported("the admitted callsite has no compiler-established "
                       "destination extent");
  if (!evidence->coverage.supported ||
      evidence->coverage.traversal != "COMPLETE")
    return Unsupported("local evidence coverage is incomplete");
  auto same_ref = [&](const O *ref, const EntityRef &expected) {
    return ref && *ref->getString("index_id") == index.id().value() &&
           *ref->get("ordinal")->getAsUINT64() == expected.ordinal;
  };
  if (capacity != extent ||
      !same_ref(operands.getObject("destination_ref"),
                operand_refs->destination) ||
      !same_ref(operands.getObject("source_ref"), operand_refs->source) ||
      !same_ref(operands.getObject("length_ref"), operand_refs->length))
    return Bad("typed operands do not match the admitted callsite evidence");

  auto harness = config.harnesses.find(harness_id);
  if (harness == config.harnesses.end())
    return Unsupported("unknown registered replay harness: " + harness_id);
  const Path harness_source = Canonical(harness->second.source);
  const Path payload_source = Canonical(harness->second.payload);
  std::error_code ec;
  if (!std::filesystem::is_regular_file(harness_source, ec) ||
      !std::filesystem::is_regular_file(payload_source, ec))
    return Unsupported("registered harness or payload is unavailable");
  auto payload_bytes = ReadBounded(payload_source, kMaxPayloadBytes);
  if (!payload_bytes.ok())
    return payload_bytes.status();
  if (HashBytes(*payload_bytes) != payload_digest)
    return Bad("registered payload content does not match the payload digest");
  if (payload_bytes->size() < readable)
    return Unsupported("registered payload is shorter than the declared "
                       "readable extent");

  const auto &input_ids = *q.getArray("input_artifact_ids");
  if (input_ids.size() != 1 ||
      *input_ids.front().getAsString() != evidence->local_evidence_id.value())
    return Bad("replay input artifacts must be the admitted local evidence");

  // Compiler and sanitizer runtime identity are required before execution.
  if (!remaining())
    return expired();
  auto compiler = InspectCompiler(config.compiler, remaining());
  if (!compiler.ok())
    return compiler.status();

  RootPaths paths;
  std::string pattern =
      (Canonical(config.work_parent) / "veritas-replay-XXXXXX").string();
  std::vector<char> buffer(pattern.begin(), pattern.end());
  buffer.push_back('\0');
  char *made = mkdtemp(buffer.data());
  if (!made)
    return Unsupported("cannot create a disposable replay directory");
  Disposable disposable;
  disposable.Set(made);
  paths.root = made;
  paths.input = paths.root / "input";
  paths.work = paths.root / "work";
  paths.harness = paths.root / "harness";
  paths.payload = paths.root / "payload";
  paths.image = paths.root / "image";
  paths.profile = paths.root / "profile.sb";
  for (const auto &directory :
       {paths.work, paths.harness, paths.payload, paths.image})
    if (!MakeDirectories(directory).ok())
      return Status::Internal("cannot create replay work directories");
  auto materialized = snapshot.Materialize(paths.input);
  if (!materialized.ok())
    return Unsupported("cannot materialize captured inputs: " +
                       std::string(materialized.message()));
  NormalizeTimestamps(paths.input);
  auto harness_copy = ReadBounded(harness_source, kMaxSourceBytes);
  if (!harness_copy.ok())
    return harness_copy.status();
  if (!WriteFile(paths.harness / "harness.cc", *harness_copy, 0400).ok())
    return Status::Internal("cannot stage the registered harness");
  NormalizeTimestamps(paths.harness);
  if (!WriteFile(paths.payload / "input.bin", *payload_bytes, 0400).ok())
    return Status::Internal("cannot stage the concrete input");
  // Producer/configuration identity binds the toolchain, the registered
  // harness bytes, the isolation kind and the execution limits.
  A denied, allowed;
  for (const auto &path : config.deny_read_paths)
    denied.emplace_back(path);
  for (const auto &path : config.read_only_paths)
    allowed.emplace_back(path);
  const std::string producer_digest = HashBytes(*CanonicalJson(
      O{{"version", config.version},
        {"compiler", compiler->digest},
        {"isolation", config.isolation},
        {"work_parent", config.work_parent},
        {"deny_read_paths", denied},
        {"read_only_paths", allowed},
        {"harness_id", harness_id},
        {"harness_digest", HashBytes(*harness_copy)},
        {"limits", O{{"wall_ms", config.limits.wall_ms},
                     {"output_bytes", config.limits.output_bytes},
                     {"rss_bytes", config.limits.rss_bytes},
                     {"max_processes", config.limits.max_processes}}}}));

  std::vector<std::string> read_only = {
      paths.input.string(), paths.harness.string(), paths.payload.string(),
      paths.image.string(), compiler->path,         compiler->runtime_path};
  if (!compiler->resource_dir.empty())
    read_only.push_back(compiler->resource_dir);
  if (!compiler->sysroot.empty())
    read_only.push_back(compiler->sysroot);
  for (const auto &path : config.read_only_paths)
    read_only.push_back(Canonical(path).string());
  std::vector<std::string> deny = {"/root"};
  if (const passwd *account = getpwuid(getuid()))
    deny.push_back(Canonical(account->pw_dir).string());
#ifdef __APPLE__
  deny.push_back("/Users");
#endif
  for (const auto &path : config.deny_read_paths)
    deny.push_back(Canonical(path).string());
  auto sandbox = PrepareSandbox(config, paths, read_only, deny);
  if (!sandbox.ok())
    return sandbox.status();

  const std::vector<std::string> environment = {"HOME=" + paths.work.string(),
                                                "TMPDIR=" + paths.work.string(),
                                                "PATH=/usr/bin:/bin",
                                                "LANG=C",
                                                "LC_ALL=C",
                                                "SOURCE_DATE_EPOCH=0"};
  ProcessLimits compile_limits;
  compile_limits.wall_ms = config.limits.wall_ms;
  compile_limits.output_bytes = config.limits.output_bytes;
  compile_limits.rss_bytes = config.limits.rss_bytes;
  compile_limits.max_processes = config.limits.max_processes;
  auto step_limits = [&]() -> StatusOr<ProcessLimits> {
    const uint64_t left = remaining();
    if (!left)
      return expired();
    ProcessLimits limits = compile_limits;
    limits.wall_ms = std::min(compile_limits.wall_ms, left);
    return limits;
  };

  // Qualify the enforcing profile with real filesystem, credential and
  // network canaries before any captured source is compiled or run.
  auto probe_source = paths.work / "probe.cc";
  const std::string probe =
      "#include <arpa/inet.h>\n"
      "#include <fcntl.h>\n"
      "#include <netinet/in.h>\n"
      "#include <cstdio>\n"
      "#include <cstdlib>\n"
      "#include <cstring>\n"
      "#include <dirent.h>\n"
      "#include <sys/socket.h>\n"
      "#include <unistd.h>\n"
      "int main(int argc,char**argv){\n"
      "  if(argc<3)return 2;\n"
      "  if(!strcmp(argv[1],\"write\")){\n"
      "    int fd=open(argv[2],O_WRONLY|O_CREAT|O_TRUNC,0600);\n"
      "    if(fd>=0){write(fd,\"x\",1);close(fd);puts(\"ALLOWED\");}\n"
      "    else puts(\"DENIED\"); return 0;}\n"
      "  if(!strcmp(argv[1],\"read\")){\n"
      "    int fd=open(argv[2],O_RDONLY);\n"
      "    if(fd>=0){close(fd);puts(\"ALLOWED\");} else puts(\"DENIED\");\n"
      "    return 0;}\n"
      "  if(!strcmp(argv[1],\"list\")){\n"
      "    DIR*d=opendir(argv[2]);\n"
      "    if(!d){puts(\"DENIED\");return 0;}\n"
      "    int any=0;\n"
      "    while(struct dirent*e=readdir(d)){\n"
      "      "
      "if(strcmp(e->d_name,\".\")&&strcmp(e->d_name,\"..\")){any=1;break;}}\n"
      "    closedir(d); puts(any?\"ALLOWED\":\"DENIED\"); return 0;}\n"
      "  if(!strcmp(argv[1],\"net\")){\n"
      "    int s=socket(AF_INET,SOCK_STREAM,0);\n"
      "    if(s<0){puts(\"DENIED\");return 0;}\n"
      "    sockaddr_in a{}; a.sin_family=AF_INET;\n"
      "    a.sin_port=htons((unsigned short)atoi(argv[2]));\n"
      "    a.sin_addr.s_addr=htonl(0x7f000001);\n"
      "    int r=connect(s,reinterpret_cast<sockaddr*>(&a),sizeof a);\n"
      "    close(s); puts(r==0?\"ALLOWED\":\"DENIED\"); return 0;}\n"
      "  return 2;}\n";
  if (!WriteFile(probe_source, probe, 0600).ok())
    return Status::Internal("cannot stage the isolation probe");
  auto probe_binary = paths.work / "probe";
  std::vector<std::string> probe_command = {compiler->path};
  if (!compiler->sysroot.empty())
    probe_command.insert(probe_command.end(), {"-isysroot", compiler->sysroot});
  probe_command.insert(probe_command.end(), {"-O0", "-o", probe_binary.string(),
                                             probe_source.string()});
  auto probe_limits = step_limits();
  if (!probe_limits.ok())
    return probe_limits.status();
  auto probe_build =
      RunBounded(probe_command, paths.work, environment, *probe_limits);
  if (!probe_build.ok() || probe_build->exit_code != 0 ||
      probe_build->timed_out)
    return Unsupported("replay compiler cannot build the isolation probe");
  auto canary =
      [&](const std::vector<std::string> &args) -> StatusOr<ProcessResult> {
    auto limits = step_limits();
    if (!limits.ok())
      return limits.status();
    std::vector<std::string> program = {probe_binary.string()};
    program.insert(program.end(), args.begin(), args.end());
    return RunBounded(
        Sandboxed(*sandbox, paths.work, program, read_only, environment),
        paths.work, environment, *limits);
  };
  const std::string canary_suffix =
      paths.root.filename().string() + "-" + std::to_string(getpid());
  const auto write_canary =
      paths.root.parent_path() / ("write-canary-" + canary_suffix);
  std::filesystem::remove(write_canary, ec);
  auto written = canary({"write", write_canary.string()});
  bool canary_present = std::filesystem::exists(write_canary, ec);
  std::filesystem::remove(write_canary, ec);
  // The host-side effect is the enforcement property. Inside bubblewrap the
  // child may create the same path in its private tmpfs while the host file
  // stays absent; a macOS denial reports DENIED. Either way the host tree must
  // remain untouched and the probe must have run.
  if (!written.ok() || written->exit_code != 0 || canary_present)
    return Unsupported("the configured isolation profile allows host writes");
  const passwd *account = getpwuid(getuid());
  if (!account)
    return Unsupported("cannot qualify credential isolation without a home");
  const std::string secret_path =
      (Path(account->pw_dir) / ("read-canary-" + canary_suffix)).string();
  if (!WriteFile(secret_path, "secret", 0600).ok())
    return Unsupported("cannot qualify credential isolation");
  auto read = canary({"read", secret_path});
  std::filesystem::remove(secret_path, ec);
  if (!read.ok() || read->exit_code != 0 ||
      read->out.find("DENIED") == std::string::npos)
    return Unsupported(
        "the configured isolation profile exposes host credentials");
  // Each denied root must actually be denied, including the live checkout.
  // A directory that is masked empty counts as denied; one that still lists
  // entries is an exposure.
  for (const auto &path : deny) {
    std::error_code status;
    if (!std::filesystem::is_directory(path, status))
      continue;
    auto listed = canary({"list", path});
    if (!listed.ok() || listed->exit_code != 0 ||
        listed->out.find("DENIED") == std::string::npos)
      return Unsupported(
          "the configured isolation profile exposes a denied path: " + path);
  }
  int listener = socket(AF_INET, SOCK_STREAM, 0);
  if (listener < 0)
    return Unsupported("cannot qualify network isolation");
  sockaddr_in address{};
  address.sin_family = AF_INET;
  address.sin_addr.s_addr = htonl(0x7f000001);
  address.sin_port = 0;
  if (bind(listener, reinterpret_cast<sockaddr *>(&address), sizeof address) !=
          0 ||
      listen(listener, 1) != 0) {
    close(listener);
    return Unsupported("cannot qualify network isolation");
  }
  socklen_t length = sizeof address;
  if (getsockname(listener, reinterpret_cast<sockaddr *>(&address), &length) !=
      0) {
    close(listener);
    return Unsupported("cannot qualify network isolation");
  }
  auto network = canary({"net", std::to_string(ntohs(address.sin_port))});
  pollfd pending{listener, POLLIN, 0};
  int ready = poll(&pending, 1, 150);
  close(listener);
  if (!network.ok() || network->exit_code != 0 || ready > 0 ||
      network->out.find("DENIED") == std::string::npos)
    return Unsupported(
        "the configured isolation profile allows host network access");

  const CapturedCompileCommand *command = nullptr;
  for (const auto &candidate : snapshot.compiler_commands())
    if (candidate.file == index.entities()[ordinal].path)
      command = &candidate;
  if (!command)
    return Unsupported("no captured compiler command for the admitted TU");
  auto admitted =
      AdmitReplayCompileCommand(snapshot, *command, paths.input.string());
  if (!admitted.ok())
    return admitted.status();

  std::vector<std::string> common = {
      compiler->path,
      "-g",
      "-O0",
      "-fno-builtin",
      "-fsanitize=address",
      "-fno-omit-frame-pointer",
      "-fdebug-compilation-dir=/veritas-work",
      "-fdebug-prefix-map=" + paths.input.string() + "/=",
      "-fdebug-prefix-map=" + paths.harness.string() + "/=",
      "-fdebug-prefix-map=" + paths.work.string() + "/="};
  if (!compiler->sysroot.empty())
    common.insert(common.end(), {"-isysroot", compiler->sysroot});
  std::vector<std::string> tu = common;
  // Keep the captured standard and semantic flags; the index applied the same
  // captured flags to its syntax-only parse, so forcing a different standard
  // would analyze a different program than it ran.
  for (const auto &flag : admitted->flags)
    tu.push_back(flag);
  tu.insert(tu.end(), {"-I", paths.input.string(),
                       "-DVERITAS_EXPECTED_CAPACITY=" + Mode(capacity),
                       "-DVERITAS_EXPECTED_READABLE=" + Mode(readable), "-x",
                       admitted->language, "-c",
                       (paths.input / admitted->source).string(), "-o",
                       (paths.work / "tu.o").string()});
  auto tu_limits = step_limits();
  if (!tu_limits.ok())
    return tu_limits.status();
  auto compiled_tu =
      RunBounded(Sandboxed(*sandbox, paths.input, tu, read_only, environment),
                 paths.input, environment, *tu_limits);
  if (compiled_tu.ok() && compiled_tu->timed_out)
    return expired();
  // The harness is trusted code. Captured macros and include directories must
  // not alter it, so it sees no captured -D/-U flags and only the captured
  // tree as a last-resort quoted-include root (system headers win).
  std::vector<std::string> harness_compile = common;
  harness_compile.insert(harness_compile.end(),
                         {"-std=c++20", "-idirafter", paths.input.string(),
                          "-DVERITAS_EXPECTED_CAPACITY=" + Mode(capacity),
                          "-DVERITAS_EXPECTED_READABLE=" + Mode(readable), "-x",
                          "c++", "-c", (paths.harness / "harness.cc").string(),
                          "-o", (paths.work / "harness.o").string()});
  StatusOr<ProcessResult> compiled_harness =
      Status::Internal("translation unit did not compile");
  if (compiled_tu.ok() && compiled_tu->exit_code == 0) {
    auto harness_limits = step_limits();
    if (!harness_limits.ok())
      return harness_limits.status();
    compiled_harness =
        RunBounded(Sandboxed(*sandbox, paths.harness, harness_compile,
                             read_only, environment),
                   paths.harness, environment, *harness_limits);
    if (compiled_harness.ok() && compiled_harness->timed_out)
      return expired();
  }
  std::vector<std::string> link_command = {compiler->path};
  if (!compiler->sysroot.empty())
    link_command.insert(link_command.end(), {"-isysroot", compiler->sysroot});
  link_command.insert(link_command.end(),
                      {"-fsanitize=address", (paths.work / "tu.o").string(),
                       (paths.work / "harness.o").string(), "-o",
                       (paths.work / "program").string()});
  StatusOr<ProcessResult> link = Status::Internal("harness did not compile");
  if (compiled_harness.ok() && compiled_harness->exit_code == 0) {
    auto link_limits = step_limits();
    if (!link_limits.ok())
      return link_limits.status();
    link = RunBounded(
        Sandboxed(*sandbox, paths.work, link_command, read_only, environment),
        paths.work, environment, *link_limits);
    if (link.ok() && link->timed_out)
      return expired();
  }

  const auto start = Clock::now();
  std::string compile_log;
  if (!compiled_tu.ok())
    compile_log = compiled_tu.status().message();
  else
    compile_log += compiled_tu->err;
  if (compiled_harness.ok())
    compile_log += compiled_harness->err;
  else
    compile_log += std::string(compiled_harness.status().message());
  if (link.ok())
    compile_log += link->err;
  else
    compile_log += std::string(link.status().message());

  const bool built = compiled_tu.ok() && compiled_tu->exit_code == 0 &&
                     compiled_harness.ok() &&
                     compiled_harness->exit_code == 0 && link.ok() &&
                     link->exit_code == 0;
  if (built) {
    // Preserve the linked image read-only before executing it. The run keeps
    // write access to its work tree, so hashing or symbolizing work/program
    // after the run would trust a file the target can replace.
    auto executable = ReadBounded(paths.work / "program", kMaxExecutableBytes);
    if (!executable.ok())
      return executable.status();
    if (!WriteFile(paths.image / "program", *executable, 0500).ok())
      return Status::Internal("cannot preserve the replay executable image");
  }
  ProcessResult run;
  if (built) {
    const uint64_t left = remaining();
    if (!left)
      return expired();
    const uint64_t run_wall =
        std::min({Number(*q.getObject("budget"), "wall_ms"),
                  config.limits.wall_ms, left});
    if (!run_wall)
      return expired();
    ProcessLimits run_limits;
    run_limits.wall_ms = run_wall;
    run_limits.output_bytes =
        std::min(Number(*q.getObject("budget"), "output_bytes"),
                 config.limits.output_bytes);
    run_limits.rss_bytes = config.limits.rss_bytes;
    run_limits.max_processes = config.limits.max_processes;
    std::vector<std::string> run_environment = environment;
    run_environment.push_back(
        "ASAN_OPTIONS=detect_leaks=0:symbolize=0:abort_on_error=1");
    auto started = RunBounded(
        Sandboxed(*sandbox, paths.work,
                  {(paths.image / "program").string(),
                   (paths.payload / "input.bin").string(), Mode(requested)},
                  read_only, run_environment),
        paths.work, run_environment, run_limits);
    if (!started.ok())
      return started.status();
    run = *started;
  }

  // Compose the closed VerificationResult.
  Artifacts artifacts;
  const std::string evidence_bytes =
      *CanonicalJson(LocalEvidenceSemanticJson(*evidence));
  artifacts.Pin(evidence->local_evidence_id.value(), evidence_bytes);
  artifacts.Add("replay-input", *payload_bytes);
  std::string executable_digest;
  if (built) {
    if (auto executable =
            ReadBounded(paths.image / "program", kMaxExecutableBytes);
        executable.ok()) {
      std::string normalized =
          NormalizeExecutable(*executable, paths.root.string());
      executable_digest = HashBytes(normalized);
      artifacts.Add("replay-executable", normalized);
      artifacts.Store("replay-executable-raw", *executable);
    }
    artifacts.Add(
        "replay-compiler",
        *CanonicalJson(O{{"path", compiler->path},
                         {"version", compiler->version},
                         {"target", compiler->target},
                         {"resource_dir", compiler->resource_dir},
                         {"runtime", compiler->runtime_path},
                         {"runtime_digest", compiler->runtime_digest}}));
    artifacts.Pin("replay-runtime:sha256:" + compiler->runtime_digest,
                  compiler->runtime_bytes);
  }
  if (!compile_log.empty())
    artifacts.Store("replay-compile-log", compile_log);
  if (!run.err.empty())
    artifacts.Store("replay-sanitizer-log", run.err);

  std::string status = "ERROR";
  std::string outcome = built ? "COMPLETED" : "ERROR";
  bool supported = false;
  std::string traversal = built ? "COMPLETE" : "INCOMPLETE";
  A frontier, reasons;
  std::string witness;
  if (!built) {
    reasons.emplace_back("replay compilation did not produce an instrumented "
                         "executable");
  } else if (run.timed_out) {
    status = "UNKNOWN";
    outcome = "TIMEOUT";
    supported = false;
    traversal = "INCOMPLETE";
    frontier.emplace_back("replay-timeout");
    reasons.emplace_back("replay exceeded the configured deadline");
  } else if (run.limit_exceeded) {
    reasons.emplace_back("replay exceeded its process/RSS/output allowance");
  } else {
    const SanitizerReport report = ParseSanitizer(run.err);
    if (report.present) {
      // The target owns its stderr. Require the sanitizer's abort path and
      // summary before treating the transcript as a sanitizer observation; a
      // forged transcript with a clean exit is not a finding. A deliberate
      // forgery that also aborts remains indistinguishable without a trusted
      // external observer (recorded as a remaining assumption).
      const bool aborted = run.exit_code == 128 + SIGABRT;
      const bool summarized =
          run.err.find("SUMMARY: AddressSanitizer:") != std::string::npos;
      if (!aborted || !summarized) {
        status = "ERROR";
        outcome = "COMPLETED";
        reasons.emplace_back("sanitizer-like output without the sanitizer "
                             "abort/summary status");
      } else {
        bool site_matches = false;
        std::string site_reason = "sanitizer finding did not name the admitted "
                                  "callsite";
        const auto &entity = index.entities()[ordinal];
        const auto source = snapshot.Read(entity.path);
        uint64_t line = source.ok() ? LineOf(*source, entity.start) : 0;
        uint64_t same_line = 0;
        for (const auto &other : index.entities())
          if (other.kind == "CALLSITE" && other.path == entity.path &&
              source.ok() && LineOf(*source, other.start) == line)
            ++same_line;
        // The platform symbolizer prints a source basename. The file identity
        // is therefore unambiguous only when no other admitted callsite shares
        // that basename; otherwise the finding cannot be attributed and stays
        // non-deciding.
        const std::string expected_site = Path(entity.path).filename().string();
        bool unique_basename = true;
        for (const auto &other : index.entities())
          if (other.path != entity.path &&
              Path(other.path).filename().string() == expected_site)
            unique_basename = false;
        if (report.write && report.size == requested && requested > capacity &&
            report.kind.find("buffer-overflow") != std::string::npos &&
            source.ok() && same_line == 1 && unique_basename) {
          for (const auto &frame : report.frames) {
            if (Canonical(frame.module) != Canonical(paths.image / "program"))
              continue;
            auto locations = Symbolize(paths.image / "program", frame);
            if (!locations.ok())
              continue;
            for (const auto &location : *locations)
              if (location.line == line &&
                  Path(location.file).filename().string() == expected_site)
                site_matches = true;
          }
        }
        if (site_matches) {
          status = "REFUTED";
          outcome = "COMPLETED";
          supported = true;
          traversal = "COMPLETE";
          // The raw report contains ASLR/PID data, so the content-addressed
          // witness pins the decisive facts instead of the whole transcript.
          Json facts = O{{"predicate_kind", "copy_bound.v1"},
                         {"kind", "ASAN_BUFFER_OVERFLOW"},
                         {"operation", "WRITE"},
                         {"bytes", report.size},
                         {"capacity_bytes", capacity},
                         {"requested_bytes", requested},
                         {"site_path", entity.path},
                         {"site_line", line},
                         {"executable_digest", executable_digest},
                         {"input_digest", payload_digest},
                         {"compiler_digest", compiler->digest},
                         {"runtime_digest", compiler->runtime_digest},
                         {"sanitizer", "address"}};
          auto canonical = CanonicalJson(facts);
          if (!canonical.ok())
            return canonical.status();
          witness = artifacts.Add("replay-witness", *canonical);
        } else {
          status = "ERROR";
          outcome = "COMPLETED";
          reasons.push_back(site_reason);
        }
      }
    } else if (run.exit_code == 0) {
      status = "UNKNOWN";
      reasons.emplace_back("replay completed without a matching sanitizer "
                           "finding; the bound was not independently "
                           "established");
    } else if (run.exit_code == 2) {
      status = "UNKNOWN";
      reasons.emplace_back("target function rejected the concrete input; a "
                           "base rejection is a control, not universal safety");
    } else {
      status = "ERROR";
      reasons.emplace_back("replay terminated without a matching sanitizer "
                           "finding");
    }
  }
  const auto &local_evidence = *evidence;
  Json verification =
      O{{"binding", ToJson(snapshot.binding())},
        {"request_digest", *VerificationRequestDigest(request)},
        {"predicate_kind", "copy_bound.v1"},
        {"typed_operands", *q.get("typed_operands")},
        {"execution_domain", *q.get("execution_domain")},
        {"producer", O{{"name", config.producer},
                       {"version", config.version},
                       {"config_digest", producer_digest}}},
        {"status", status},
        {"proposition", "REQUESTED_LE_CAPACITY"},
        {"certificate_artifact_ids", A{}},
        {"counterexample_artifact_ids", witness.empty() ? A{} : A{witness}},
        {"input_dependencies", artifacts.dependencies},
        {"assumptions", *q.get("assumptions")},
        {"coverage", O{{"supported", supported},
                       {"scope_closed", false},
                       {"traversal", traversal},
                       {"frontier_refs", frontier},
                       {"reasons", reasons},
                       {"examined", local_evidence.coverage.examined}}},
        {"operational_outcome", outcome}};
  auto verification_id = VerificationResultId(verification);
  if (!verification_id.ok())
    return verification_id.status();
  std::get<O>(verification.data)["verification_id"] = *verification_id;

  ReplayResult result;
  result.verification = std::move(verification);
  result.artifacts = std::move(artifacts.bytes);
  result.exit_code = built ? run.exit_code : -1;
  result.timed_out = run.timed_out;
  result.compiled = built;
  auto encoded = CanonicalJson(result.verification);
  uint64_t output_bytes = run.out.size() + run.err.size() + compile_log.size();
  if (encoded.ok())
    output_bytes += encoded->size();
  const uint64_t wall_ms =
      static_cast<uint64_t>(
          std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now() -
                                                                start)
              .count()) +
      1;
  result.usage = Usage{
      wall_ms,
      (compiled_tu.ok() ? compiled_tu->cpu_ms : 0) +
          (compiled_harness.ok() ? compiled_harness->cpu_ms : 0) +
          (link.ok() ? link->cpu_ms : 0) + run.cpu_ms,
      std::max({compiled_tu.ok() ? compiled_tu->peak_rss_bytes : 0,
                compiled_harness.ok() ? compiled_harness->peak_rss_bytes : 0,
                link.ok() ? link->peak_rss_bytes : 0, run.peak_rss_bytes}),
      output_bytes, evidence->coverage.examined};
  return result;
}
