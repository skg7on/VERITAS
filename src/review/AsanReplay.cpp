// Profile text is generated by quoting paths; a quote or newline in a path
// would rewrite the policy. Operator paths are trusted, but the disposable tree
// and derived roots are still checked before policy text is built.
bool ProfileSafe(std::string_view path) {
  return path.find_first_of("\"\n\r") == std::string_view::npos &&
         path.find('\0') == std::string_view::npos;
}
Path Canonical(const Path &path) {
  std::error_code ec;
  auto resolved = std::filesystem::weakly_canonical(path, ec);
  return ec ? path.lexically_normal() : resolved;
}
StatusOr<std::string> ReadBounded(const Path &path, uint64_t limit) {
  int fd = open(path.c_str(), O_RDONLY | O_CLOEXEC | O_NOFOLLOW);
  if (fd < 0)
    return Unsupported("cannot read " + path.string());
  struct stat st{};
  if (fstat(fd, &st) != 0 || !S_ISREG(st.st_mode) ||
      static_cast<uint64_t>(st.st_size) > limit) {
    close(fd);
    return Unsupported("not a bounded regular file: " + path.string());
  }
  std::string bytes;
  bytes.reserve(static_cast<size_t>(st.st_size));
  char buffer[65536];
  for (;;) {
    ssize_t n = read(fd, buffer, sizeof buffer);
    if (n < 0 && errno == EINTR)
      continue;
    if (n < 0) {
      close(fd);
      return Unsupported("cannot read " + path.string());
    }
    if (n == 0)
      break;
    if (bytes.size() + static_cast<size_t>(n) > limit) {
      close(fd);
      return Unsupported("file exceeds replay limit: " + path.string());
    }
    bytes.append(buffer, static_cast<size_t>(n));
  }
  close(fd);
  return bytes;
}
Status WriteFile(const Path &path, std::string_view bytes, mode_t mode) {
  int fd = open(path.c_str(), O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC, mode);
  if (fd < 0)
    return Status::Internal("cannot create " + path.string());
  size_t offset = 0;
  while (offset < bytes.size()) {
    ssize_t n = write(fd, bytes.data() + offset, bytes.size() - offset);
    if (n < 0 && errno == EINTR)
      continue;
    if (n <= 0) {
      close(fd);
      return Status::Internal("cannot write " + path.string());
    }
    offset += static_cast<size_t>(n);
  }
  close(fd);
  return Status::Ok();
}
// ELF DWARF line tables may record source mtimes; freshly materialized inputs
// would otherwise change the linked executable between identical replays.
void NormalizeTimestamps(const Path &root) {
  std::error_code ec;
  const timespec epoch[2] = {{0, 0}, {0, 0}};
  for (auto it = std::filesystem::recursive_directory_iterator(root, ec);
       !ec && it != std::filesystem::recursive_directory_iterator();
       it.increment(ec))
    utimensat(AT_FDCWD, it->path().c_str(), epoch, AT_SYMLINK_NOFOLLOW);
  utimensat(AT_FDCWD, root.c_str(), epoch, AT_SYMLINK_NOFOLLOW);
}
Status MakeDirectories(const Path &path, mode_t mode = 0700) {
  std::error_code ec;
  std::filesystem::create_directories(path, ec);
  if (ec)
    return Status::Internal("cannot create directory " + path.string());
  std::filesystem::permissions(path, static_cast<std::filesystem::perms>(mode),
                               std::filesystem::perm_options::replace, ec);
  return Status::Ok();
}
class Disposable {
public:
  ~Disposable() {
    if (path_.empty())
      return;
    std::error_code ec;
    for (auto it = std::filesystem::recursive_directory_iterator(path_, ec);
         !ec && it != std::filesystem::recursive_directory_iterator();
         it.increment(ec)) {
      // The target can create symlinks in its writable tree. Never follow one
      // while restoring permissions; only directories this producer created
      // are chmodded.
      std::error_code kind;
      if (it->symlink_status(kind).type() ==
              std::filesystem::file_type::directory &&
          !kind)
        std::filesystem::permissions(
            it->path(), std::filesystem::perms::owner_all,
            std::filesystem::perm_options::replace, ec);
    }
    std::filesystem::remove_all(path_, ec);
  }
  void Set(Path path) { path_ = std::move(path); }
  const Path &path() const { return path_; }

private:
  Path path_;
};

struct ProcessLimits {
  uint64_t wall_ms = 60000, output_bytes = 1024 * 1024,
           rss_bytes = 1024ull * 1024 * 1024, max_processes = 16;
};
struct ProcessResult {
  bool timed_out = false, limit_exceeded = false;
  int exit_code = -1;
  std::string out, err;
  uint64_t wall_ms = 0, cpu_ms = 0, peak_rss_bytes = 0;
};
struct ProcessRow {
  pid_t pid = 0, parent = 0, group = 0;
  uint64_t rss = 0;
};
std::vector<ProcessRow> ProcessTable() {
  std::vector<ProcessRow> rows;
#ifdef __APPLE__
  int bytes = proc_listallpids(nullptr, 0);
  if (bytes <= 0)
    return rows;
  std::vector<pid_t> pids(static_cast<size_t>(bytes) / sizeof(pid_t) + 32);
  bytes = proc_listallpids(pids.data(),
                           static_cast<int>(pids.size() * sizeof(pid_t)));
  if (bytes <= 0)
    return rows;
  const size_t size = static_cast<size_t>(bytes) / sizeof(pid_t);
  for (size_t i = 0; i < size; ++i) {
    pid_t pid = pids[i];
    if (pid <= 0)
      continue;
    proc_bsdinfo bsd{};
    proc_taskinfo task{};
    if (proc_pidinfo(pid, PROC_PIDTBSDINFO, 0, &bsd, sizeof bsd) != sizeof bsd)
      continue;
    rows.push_back({pid, static_cast<pid_t>(bsd.pbi_ppid), getpgid(pid),
                    proc_pidinfo(pid, PROC_PIDTASKINFO, 0, &task,
                                 sizeof task) == sizeof task
                        ? task.pti_resident_size
                        : 0});
  }
#else
  DIR *directory = opendir("/proc");
  if (!directory)
    return rows;
  while (dirent *entry = readdir(directory)) {
    char *end = nullptr;
    long pid = std::strtol(entry->d_name, &end, 10);
    if (!end || *end || pid <= 0)
      continue;
    std::ifstream stat("/proc/" + std::to_string(pid) + "/stat");
    std::string line;
    if (!std::getline(stat, line))
      continue;
    const auto close = line.rfind(')');
    if (close == std::string::npos)
      continue;
    std::istringstream fields(line.substr(close + 2));
    std::string state;
    long parent = 0, group = 0;
    fields >> state >> parent >> group;
    std::string token;
    for (int i = 0; i < 18; ++i)
      fields >> token;
    uint64_t pages = 0;
    fields >> pages;
    rows.push_back({static_cast<pid_t>(pid), static_cast<pid_t>(parent),
                    static_cast<pid_t>(group),
                    pages * static_cast<uint64_t>(sysconf(_SC_PAGESIZE))});
  }
  closedir(directory);
#endif
  return rows;
}
uint64_t SampleGroup(pid_t leader, uint64_t *count,
                     std::set<pid_t> *descendants) {
  const std::vector<ProcessRow> rows = ProcessTable();
  std::set<pid_t> members;
  for (const auto &row : rows)
    if (row.pid == leader || row.group == leader)
      members.insert(row.pid);
  bool changed = true;
  while (changed) {
    changed = false;
    for (const auto &row : rows)
      if (!members.contains(row.pid) &&
          (members.contains(row.parent) || row.parent == leader)) {
        members.insert(row.pid);
        changed = true;
      }
  }
  uint64_t rss = 0;
  *count = 0;
  for (const auto &row : rows)
    if (members.contains(row.pid)) {
      ++*count;
      rss += row.rss;
      if (row.pid != leader)
        descendants->insert(row.pid);
    }
  return rss;
}
StatusOr<ProcessResult> RunBounded(const std::vector<std::string> &argv,
                                   const Path &working,
                                   const std::vector<std::string> &environment,
                                   const ProcessLimits &limits) {
  if (argv.empty())
    return Status::Internal("empty replay argv");
  int output[2], error[2];
  if (pipe(output) != 0)
    return Status::Internal("replay pipe failed");
  if (pipe(error) != 0) {
    close(output[0]);
    close(output[1]);
    return Status::Internal("replay pipe failed");
  }
  const auto start = Clock::now();
  pid_t pid = fork();
  if (pid < 0) {
    close(output[0]);
    close(output[1]);
    close(error[0]);
    close(error[1]);
    return Status::Internal("replay fork failed");
  }
  if (pid == 0) {
    setpgid(0, 0);
    int input = open("/dev/null", O_RDONLY);
    if (input >= 0) {
      dup2(input, STDIN_FILENO);
      close(input);
    }
    dup2(output[1], STDOUT_FILENO);
    dup2(error[1], STDERR_FILENO);
    close(output[0]);
    close(output[1]);
    close(error[0]);
    close(error[1]);
    // Nothing from the host may leak past the replay boundary.
    const long limit = std::min<long>(sysconf(_SC_OPEN_MAX), 4096);
    for (long fd = STDERR_FILENO + 1; fd < limit; ++fd)
      close(static_cast<int>(fd));
    if (chdir(working.c_str()) != 0)
      _exit(126);
    rlimit core{0, 0};
    setrlimit(RLIMIT_CORE, &core);
    std::vector<char *> args;
    for (const auto &argument : argv)
      args.push_back(const_cast<char *>(argument.c_str()));
    args.push_back(nullptr);
    std::vector<char *> env;
    for (const auto &entry : environment)
      env.push_back(const_cast<char *>(entry.c_str()));
    env.push_back(nullptr);
    execve(args[0], args.data(), env.data());
    _exit(127);
  }
  setpgid(pid, pid);
  close(output[1]);
  close(error[1]);
  for (int fd : {output[0], error[0]})
    fcntl(fd, F_SETFL, O_NONBLOCK);
  ProcessResult result;
  std::string *streams[2] = {&result.out, &result.err};
  const int fds[2] = {output[0], error[0]};
  bool open_fds[2] = {true, true};
  bool reaped = false;
  int status = 0;
  rusage usage{};
  auto now = [&]() {
    return static_cast<uint64_t>(
        std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now() -
                                                              start)
            .count());
  };
  auto next_sample = start;
  bool drain_set = false;
  uint64_t drain_deadline = 0;
  std::set<pid_t> descendants;
  while (!reaped || open_fds[0] || open_fds[1]) {
    if (!result.timed_out && !result.limit_exceeded && now() >= limits.wall_ms)
      result.timed_out = true;
    if (result.timed_out || result.limit_exceeded) {
      kill(-pid, SIGKILL);
      if (!reaped && wait4(pid, &status, 0, &usage) == pid)
        reaped = true;
      if (reaped)
        break;
    }
    if (reaped && (open_fds[0] || open_fds[1])) {
      if (!drain_set) {
        drain_deadline = now() + 250;
        drain_set = true;
      } else if (now() >= drain_deadline) {
        // A descendant still holds a pipe. Kill the group and stop draining.
        kill(-pid, SIGKILL);
        break;
      }
    }
    if (Clock::now() >= next_sample) {
      uint64_t count = 0;
      uint64_t rss = SampleGroup(pid, &count, &descendants);
      result.peak_rss_bytes = std::max(result.peak_rss_bytes, rss);
      if (rss > limits.rss_bytes || count > limits.max_processes)
        result.limit_exceeded = true;
      next_sample = Clock::now() + std::chrono::milliseconds(100);
    }
    pollfd pollers[2];
    int count = 0;
    for (int i = 0; i < 2; ++i)
      if (open_fds[i])
        pollers[count++] = pollfd{fds[i], POLLIN | POLLHUP, 0};
    if (count > 0) {
      if (poll(pollers, static_cast<nfds_t>(count), 20) > 0) {
        for (int i = 0; i < 2; ++i) {
          if (!open_fds[i])
            continue;
          char buffer[8192];
          for (;;) {
            ssize_t n = read(fds[i], buffer, sizeof buffer);
            if (n > 0) {
              streams[i]->append(buffer, static_cast<size_t>(n));
              if (result.out.size() + result.err.size() > limits.output_bytes) {
                result.limit_exceeded = true;
                break;
              }
              continue;
            }
            if (n == 0)
              open_fds[i] = false;
            break;
          }
        }
      }
    } else {
      // Both streams closed but the process has not exited; avoid a spin.
      usleep(10000);
    }
    if (!reaped) {
      pid_t waited = wait4(pid, &status, WNOHANG, &usage);
      if (waited == pid)
        reaped = true;
      else if (waited < 0 && errno != EINTR)
        reaped = true;
    }
  }
  // No descendant of a replay may outlive its leader. A process that called
  // setsid escapes the process group, so kill every remembered descendant too
  // (sampling is best-effort for children that reparent before a sample).
  for (pid_t child : descendants)
    if (child > 1)
      kill(child, SIGKILL);
  if (reaped)
    kill(-pid, SIGKILL);
  close(output[0]);
  close(error[0]);
  if (reaped) {
    if (WIFEXITED(status))
      result.exit_code = WEXITSTATUS(status);
    else if (WIFSIGNALED(status))
      result.exit_code = 128 + WTERMSIG(status);
  }
  if (result.timed_out || result.limit_exceeded)
    result.exit_code = -1;
  result.wall_ms = now();
  auto micros = [](timeval value) {
    return static_cast<uint64_t>(value.tv_sec) * 1000000 +
           static_cast<uint64_t>(value.tv_usec);
  };
  result.cpu_ms =
      (micros(usage.ru_utime) + micros(usage.ru_stime) + 999) / 1000;
  uint64_t max_rss = 0;
#ifdef __APPLE__
  max_rss = static_cast<uint64_t>(usage.ru_maxrss);
#else
  max_rss = static_cast<uint64_t>(usage.ru_maxrss) * 1024;
#endif
  result.peak_rss_bytes = std::max(result.peak_rss_bytes, max_rss);
  return result;
}

struct CompilerIdentity {
  std::string path, version, target, resource_dir, sysroot, runtime_path,
      runtime_digest, runtime_bytes, digest;
};
StatusOr<CompilerIdentity> InspectCompiler(const std::string &compiler,
                                           uint64_t wall_ms) {
  if (compiler.empty() || compiler.front() != '/')
    return Unsupported("replay compiler must be an absolute path");
  const auto start = Clock::now();
  auto left = [&]() -> uint64_t {
    const uint64_t elapsed = static_cast<uint64_t>(
        std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now() -
                                                              start)
            .count());
    return wall_ms <= elapsed ? 0 : wall_ms - elapsed;
  };
  auto step = [&]() -> StatusOr<ProcessLimits> {
    const uint64_t remaining = left();
    if (!remaining)
      return Status::DeadlineExceeded(
          "replay compiler inspection exceeded its budget");
    return ProcessLimits{std::min<uint64_t>(remaining, 10000), 65536,
                         256 * 1024 * 1024, 8};
  };
  auto run = [&](const std::vector<std::string> &argv) {
    auto limits = step();
    if (!limits.ok())
      return StatusOr<ProcessResult>(limits.status());
    auto result = RunBounded(
        argv, "/", {"PATH=/usr/bin:/bin", "LANG=C", "LC_ALL=C"}, *limits);
    if (result.ok() && result->timed_out)
      return StatusOr<ProcessResult>(Status::DeadlineExceeded(
          "replay compiler inspection exceeded its budget"));
    return result;
  };
  Path resolved = Canonical(compiler);
  std::error_code ec;
  if (!std::filesystem::is_regular_file(resolved, ec) ||
      access(resolved.c_str(), X_OK) != 0)
    return Unsupported("replay compiler is unavailable: " + compiler);
  auto version = run({resolved.string(), "--version"});
  if (!version.ok())
    return version.status();
  if (version->exit_code != 0 || version->out.empty())
    return Unsupported("replay compiler is unavailable: " + compiler);
  CompilerIdentity identity;
  // Execute the configured driver path, never the resolved symlink: clang
  // selects C++ mode from argv[0].
  identity.path = compiler;
  identity.version = version->out.substr(0, version->out.find('\n'));
  auto target = run({identity.path, "-dumpmachine"});
  if (!target.ok())
    return target.status();
  if (target->exit_code == 0) {
    std::string line = target->out;
    while (!line.empty() && (line.back() == '\n' || line.back() == '\r'))
      line.pop_back();
    identity.target = line;
  }
  if (identity.target.empty())
    return Unsupported("cannot determine the replay target for " + compiler);
  auto resource = run({identity.path, "-print-resource-dir"});
  if (!resource.ok())
    return resource.status();
  if (resource->exit_code == 0) {
    std::string line = resource->out;
    while (!line.empty() && (line.back() == '\n' || line.back() == '\r'))
      line.pop_back();
    if (!line.empty() && line.front() == '/')
      identity.resource_dir = Canonical(line).string();
  }
#ifdef __APPLE__
  // The real CLT driver needs an explicit SDK; this avoids the xcrun cache
  // that a sandboxed invocation cannot write.
  auto sdk = run({"/usr/bin/xcrun", "--show-sdk-path"});
  if (!sdk.ok())
    return sdk.status();
  if (sdk->exit_code == 0) {
    std::string line = sdk->out;
    while (!line.empty() && (line.back() == '\n' || line.back() == '\r'))
      line.pop_back();
    std::error_code sdk_ec;
    if (!line.empty() && line.front() == '/' &&
        std::filesystem::is_directory(line, sdk_ec))
      identity.sysroot = Canonical(line).string();
  }
#endif
  std::vector<std::string> names;
#ifdef __APPLE__
  names = {"libclang_rt.asan_osx_dynamic.dylib"};
#else
  names = {"libclang_rt.asan-x86_64.a", "libclang_rt.asan-aarch64.a",
           "libclang_rt.asan.so", "libclang_rt.asan-x86_64.so"};
#endif
  for (const auto &name : names) {
    StatusOr<ProcessResult> found = Status::Internal("unqueried");
    for (const char *flag : {"--print-file-name", "-print-file-name"}) {
      found = run({identity.path, flag, name});
      if (!found.ok())
        return found.status();
      if (found->exit_code == 0 && !found->out.empty())
        break;
    }
    if (found->exit_code != 0)
      continue;
    std::string line = found->out;
    while (!line.empty() && (line.back() == '\n' || line.back() == '\r'))
      line.pop_back();
    if (line.empty() || line.front() != '/')
      continue;
    Path runtime = Canonical(line);
    if (!std::filesystem::is_regular_file(runtime, ec))
      continue;
    auto bytes = ReadBounded(runtime, kMaxRuntimeBytes);
    if (!bytes.ok())
      continue;
    identity.runtime_path = runtime.string();
    identity.runtime_digest = HashBytes(*bytes);
    identity.runtime_bytes = *bytes;
    break;
  }
  if (identity.runtime_path.empty())
    return Unsupported("AddressSanitizer runtime is unavailable for " +
                       compiler);
  identity.digest =
      HashBytes(*CanonicalJson(O{{"path", identity.path},
                                 {"resolved", resolved.string()},
                                 {"version", identity.version},
                                 {"target", identity.target},
                                 {"resource_dir", identity.resource_dir},
                                 {"sysroot", identity.sysroot},
                                 {"runtime", identity.runtime_path},
                                 {"runtime_digest", identity.runtime_digest}}));
  return identity;
}

struct RootPaths {
  Path root, input, work, harness, payload, image, profile;
};
class Sandbox {
public:
  std::string kind;
  Path profile;
  Path work_root;
  std::vector<std::string> deny;
  bool linux_bwrap = false;
  std::string bwrap;
};
StatusOr<Sandbox> PrepareSandbox(const ReplayConfig &config,
                                 const RootPaths &paths,
                                 const std::vector<std::string> &read_only,
                                 const std::vector<std::string> &deny) {
  for (const auto &path : deny)
    if (!ProfileSafe(path))
      return Unsupported("unsafe path in the isolation policy");
  for (const auto &path : read_only)
    if (!ProfileSafe(path))
      return Unsupported("unsafe path in the isolation policy");
  if (!ProfileSafe(paths.root.string()))
    return Unsupported("unsafe disposable replay path");
  Sandbox sandbox;
  sandbox.kind = config.isolation;
  sandbox.work_root = paths.work;
  sandbox.deny = deny;
  if (config.isolation == kMacIsolation) {
#ifdef __APPLE__
    if (access("/usr/bin/sandbox-exec", X_OK) != 0)
      return Unsupported("sandbox-exec is unavailable");
    // Last matching rule wins: read-only allowances precede the credential /
    // live-checkout denies, so an operator path nested under a denied root
    // cannot re-open it.
    std::string profile = "(version 1)\n(allow default)\n(deny signal)\n"
                          "(allow signal (target self))\n(deny network*)\n"
                          "(deny file-write*)\n";
    profile += "(allow file-write* (subpath \"" + paths.work.string() +
               "\") (literal \"/dev/null\") (literal \"/dev/urandom\") "
               "(literal \"/dev/random\"))\n";
    for (const auto &path : read_only)
      profile += "(allow file-read* (subpath \"" + path + "\"))\n";
    profile += "(allow file-read* (subpath \"" + paths.root.string() + "\"))\n";
    for (const auto &path : deny)
      profile += "(deny file-read* (subpath \"" + path + "\"))\n";
    sandbox.profile = paths.profile;
    auto written = WriteFile(sandbox.profile, profile, 0600);
    if (!written.ok())
      return written;
    return sandbox;
#else
    return Unsupported("macOS sandbox is unavailable on this host");
#endif
  }
  if (config.isolation == kLinuxIsolation) {
#ifndef __APPLE__
    for (const char *candidate : {"/usr/bin/bwrap", "/bin/bwrap"})
      if (access(candidate, X_OK) == 0)
        sandbox.bwrap = candidate;
    if (sandbox.bwrap.empty())
      return Unsupported("bubblewrap is unavailable");
    sandbox.linux_bwrap = true;
    return sandbox;
#else
    return Unsupported("bubblewrap is unavailable on this host");
#endif
  }
  return Unsupported("no enforcing isolation profile configured");
}
std::vector<std::string>
Sandboxed(const Sandbox &sandbox, const Path &working,
          const std::vector<std::string> &program,
          const std::vector<std::string> &read_only,
          const std::vector<std::string> &environment) {
  std::vector<std::string> command;
  if (sandbox.linux_bwrap) {
    command = {sandbox.bwrap,   "--unshare-all", "--die-with-parent",
               "--new-session", "--cap-drop",    "ALL"};
    // The sandbox root starts empty; /tmp is only visible through the
    // explicit binds below, and no bind point is inside an unmounted tree.
    command.insert(command.end(),
                   {"--ro-bind-try", "/usr", "/usr", "--ro-bind-try", "/bin",
                    "/bin", "--ro-bind-try", "/lib", "/lib", "--ro-bind-try",
                    "/lib64", "/lib64", "--ro-bind-try", "/etc", "/etc",
                    "--ro-bind-try", "/sys", "/sys"});
    for (const auto &path : read_only)
      command.insert(command.end(), {"--ro-bind-try", path, path});
    // Mask every deny root after the read-only binds; a declared toolchain
    // path nested under home must not re-expose it.
    for (const auto &path : sandbox.deny)
      command.insert(command.end(), {"--tmpfs", path});
    // The disposable work tree is the only writable mount.
    command.insert(command.end(),
                   {"--bind", sandbox.work_root.string(),
                    sandbox.work_root.string(), "--dev", "/dev", "--proc",
                    "/proc", "--chdir", working.string(), "--"});
    for (const auto &argument : program)
      command.push_back(argument);
    return command;
  }
  command = {"/usr/bin/sandbox-exec", "-f", sandbox.profile.string(), "--"};
  for (const auto &argument : program)
    command.push_back(argument);
  (void)environment;
  return command;
}

struct SanitizerReport {
  bool present = false;
  std::string kind;
  bool write = false;
  uint64_t size = 0;
  std::vector<SanitizerFrameLocation> frames;
};
SanitizerReport ParseSanitizer(std::string_view text) {
  SanitizerReport report;
  const auto marker = text.find("ERROR: AddressSanitizer: ");
  if (marker == std::string_view::npos)
    return report;
  report.present = true;
  size_t start = marker + std::strlen("ERROR: AddressSanitizer: ");
  size_t end = text.find(' ', start);
  if (end == std::string_view::npos)
    end = text.size();
  report.kind = std::string(text.substr(start, end - start));
  const auto write = text.find("WRITE of size ", marker);
  if (write != std::string_view::npos) {
    report.write = true;
    size_t at = write + std::strlen("WRITE of size ");
    uint64_t value = 0;
    while (at < text.size() && text[at] >= '0' && text[at] <= '9') {
      value = value * 10 + static_cast<uint64_t>(text[at] - '0');
      ++at;
    }
    report.size = value;
  }
  report.frames = ParseSanitizerFrameLocations(text.substr(marker));
  return report;
}
struct SourceLocation {
  std::string file;
  uint64_t line = 0;
};
StatusOr<std::vector<SourceLocation>>
Symbolize(const Path &program, const SanitizerFrameLocation &frame) {
  const std::vector<std::string> environment = {"PATH=/usr/bin:/bin", "LANG=C",
                                                "LC_ALL=C"};
  ProcessLimits limits;
  limits.wall_ms = 10000;
  limits.output_bytes = 65536;
  std::vector<std::string> command;
#ifdef __APPLE__
  command = {"/usr/bin/atos", "-o", program.string()};
  if (!frame.architecture.empty())
    command.insert(command.end(), {"-arch", frame.architecture});
  command.push_back(Hex(frame.offset));
#else
  command = {"/usr/bin/addr2line", "-e", program.string(), "-f", "-C", "-i",
             Hex(frame.offset)};
#endif
  auto run = RunBounded(command, "/", environment, limits);
  if (!run.ok() || run->exit_code != 0)
    return Unsupported("no trusted symbolizer resolved the replay frame");
  std::vector<SourceLocation> locations;
  size_t start = 0;
  while (start <= run->out.size()) {
    size_t end = run->out.find('\n', start);
    if (end == std::string::npos)
      end = run->out.size();
    std::string line = run->out.substr(start, end - start);
    const auto colon = line.rfind(':');
    if (colon != std::string::npos && colon + 1 < line.size()) {
      size_t cursor = colon + 1;
      uint64_t number = 0;
      size_t digits = 0;
      while (cursor < line.size() && line[cursor] >= '0' &&
             line[cursor] <= '9') {
        number = number * 10 + static_cast<uint64_t>(line[cursor] - '0');
        ++cursor;
        ++digits;
      }
      if (digits > 0 && number > 0) {
        size_t begin = 0;
        const auto open = line.rfind('(', colon);
        if (open != std::string::npos)
          begin = open + 1;
        std::string file = line.substr(begin, colon - begin);
        while (!file.empty() && (file.front() == ' ' || file.back() == ' '))
          file.erase(file.begin());
        if (!file.empty())
          locations.push_back({std::move(file), number});
      }
    }
    if (end == run->out.size())
      break;
    start = end + 1;
  }
  if (locations.empty())
    return Unsupported("no line information named the replay frame");
  return locations;
}
// The compiler records the disposable output path in ASan module metadata and
// the platform linker signs the result. Both are occurrence data: canonicalize
// them so an identical admitted input, harness and toolchain produce the same
// executable digest. Raw bytes are retained separately.
std::string NormalizeExecutable(std::string bytes, std::string_view root) {
  const std::string marker(root.size(), '#');
  size_t at = 0;
  while (!root.empty() && (at = bytes.find(root, at)) != std::string::npos) {
    bytes.replace(at, root.size(), marker);
    at += marker.size();
  }
  if (bytes.size() < 32)
    return bytes;
  auto read32 = [&](size_t offset) -> uint32_t {
    return static_cast<uint32_t>(static_cast<unsigned char>(bytes[offset])) |
           (static_cast<uint32_t>(static_cast<unsigned char>(bytes[offset + 1]))
            << 8) |
           (static_cast<uint32_t>(static_cast<unsigned char>(bytes[offset + 2]))
            << 16) |
           (static_cast<uint32_t>(static_cast<unsigned char>(bytes[offset + 3]))
            << 24);
  };
  const uint32_t magic = read32(0);
  const bool mach64 = magic == 0xfeedfacf;
  const bool mach32 = magic == 0xfeedface;
  if (!mach64 && !mach32) {
    // ELF build-id notes are hashes of the pre-normalized output, so the note
    // still differs after the disposable root path is canonicalized. The note
    // is an occurrence identifier, not program content; zero it.
    if (bytes.size() >= 64 && static_cast<unsigned char>(bytes[0]) == 0x7f &&
        bytes.substr(1, 3) == "ELF" && bytes[5] == 1) {
      const bool elf64 = bytes[4] == 2;
      auto read16 = [&](size_t offset) -> uint32_t {
        return static_cast<uint32_t>(
                   static_cast<unsigned char>(bytes[offset])) |
               (static_cast<uint32_t>(
                    static_cast<unsigned char>(bytes[offset + 1]))
                << 8);
      };
      auto read64 = [&](size_t offset) -> uint64_t {
        return static_cast<uint64_t>(read32(offset)) |
               (static_cast<uint64_t>(read32(offset + 4)) << 32);
      };
      const uint64_t shoff = elf64 ? read64(0x28) : read32(0x20);
      const uint32_t shentsize = read16(elf64 ? 0x3a : 0x2e);
      const uint32_t shnum = read16(elf64 ? 0x3c : 0x30);
      const uint32_t shstrndx = read16(elf64 ? 0x3e : 0x32);
      if (shoff < bytes.size() && shentsize >= (elf64 ? 64 : 40) && shnum &&
          shstrndx < shnum &&
          shoff + static_cast<uint64_t>(shentsize) * shnum <= bytes.size()) {
        const size_t strings_header = shoff + shentsize * shstrndx;
        const uint64_t strings_offset =
            elf64 ? read64(strings_header + 24) : read32(strings_header + 16);
        const uint64_t strings_size =
            elf64 ? read64(strings_header + 32) : read32(strings_header + 20);
        if (strings_offset < bytes.size() &&
            strings_size <= bytes.size() - strings_offset) {
          for (uint32_t i = 0; i < shnum; ++i) {
            const size_t header = shoff + static_cast<size_t>(shentsize) * i;
            const uint64_t name_offset = read32(header);
            if (name_offset >= strings_size)
              continue;
            const size_t name_at = strings_offset + name_offset;
            const size_t name_end = bytes.find('\0', name_at);
            if (name_end == std::string::npos ||
                name_end > strings_offset + strings_size)
              continue;
            if (bytes.compare(name_at, name_end - name_at,
                              ".note.gnu.build-id") != 0)
              continue;
            const uint64_t offset =
                elf64 ? read64(header + 24) : read32(header + 16);
            const uint64_t size =
                elf64 ? read64(header + 32) : read32(header + 20);
            if (offset <= bytes.size() && size <= bytes.size() - offset)
              bytes.replace(offset, size, std::string(size, '\0'));
          }
        }
      }
    }
    return bytes;
  }
  const uint32_t count = read32(16);
  const size_t header = mach64 ? 32 : 28;
  size_t offset = header;
  for (uint32_t i = 0; i < count && offset + 8 <= bytes.size(); ++i) {
    const uint32_t command = read32(offset);
    const uint32_t size = read32(offset + 4);
    if (size < 8 || offset + size > bytes.size())
      break;
    if (command == 0x1d && offset + 16 <= bytes.size()) {
      const uint32_t data = read32(offset + 8);
      const uint32_t length = read32(offset + 12);
      if (data <= bytes.size() && length <= bytes.size() - data)
        bytes.replace(data, length, std::string(length, '\0'));
    }
    if (command == 0x1b && offset + 8 + 16 <= bytes.size())
      bytes.replace(offset + 8, 16, std::string(16, '\0'));
    // The symbol/link-edit segment carries linker-generated symbol ordinals and
    // the signature; neither is part of the loadable program.
    if ((command == 0x19 && mach64 && offset + 56 <= bytes.size()) ||
        (command == 0x01 && mach32 && offset + 40 <= bytes.size())) {
      const size_t name_offset = offset + 8;
      std::string segment(bytes.substr(name_offset, 16));
      segment.resize(segment.find('\0'));
      if (segment == "__LINKEDIT") {
        uint64_t start = 0, length = 0;
        if (mach64) {
          start = static_cast<uint64_t>(read32(offset + 40)) |
                  (static_cast<uint64_t>(read32(offset + 44)) << 32);
          length = static_cast<uint64_t>(read32(offset + 48)) |
                   (static_cast<uint64_t>(read32(offset + 52)) << 32);
        } else {
          start = read32(offset + 32);
          length = read32(offset + 36);
        }
        if (start <= bytes.size() && length <= bytes.size() - start)
          bytes.replace(start, length, std::string(length, '\0'));
      }
    }
    offset += size;
  }
  return bytes;
}
uint64_t LineOf(std::string_view source, uint64_t offset) {
  uint64_t line = 1;
  for (uint64_t i = 0; i < offset && i < source.size(); ++i)
    if (source[i] == '\n')
      ++line;
  return line;
}

struct Artifacts {
  std::map<std::string, std::string> bytes;
  A dependencies;
  std::string Add(std::string prefix, std::string_view content) {
    const std::string digest = HashBytes(content);
    const std::string id = prefix + ":sha256:" + digest;
    if (bytes.emplace(id, std::string(content)).second)
      dependencies.emplace_back(
          O{{"artifact_id", id}, {"content_digest", digest}});
    return id;
  }
  std::string Pin(std::string id, std::string_view content) {
    const std::string digest = HashBytes(content);
    if (bytes.emplace(id, std::string(content)).second)
      dependencies.emplace_back(
          O{{"artifact_id", id}, {"content_digest", digest}});
    return id;
  }
  // Retains supporting bytes without making them part of the content address.
  std::string Store(std::string prefix, std::string_view content) {
    const std::string digest = HashBytes(content);
    const std::string id = prefix + ":sha256:" + digest;
    bytes.emplace(id, std::string(content));
    return id;
  }
};

